/*Write a program to read one float and one int value from user and find the larger value from
 it using Command Line arguments*/
 
 class value
 {
	public static void main(String x[])
	{
		
		float f = Float.parseFloat(x[0]);
		int n = Integer.parseInt(x[1]);
		
		System.out.println(f);
		System.out.println(n);
	}
 }